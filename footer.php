    document.addEventListener('DOMContentLoaded', function() {
        // Mobile Navigation Drawer Handlers
        var mobileNavToggle = document.getElementById('mobileNavToggle');
        var mobileDrawer = document.getElementById('mobileDrawer');
        var mobileDrawerOverlay = document.getElementById('mobileDrawerOverlay');
        var closeMobileDrawer = document.getElementById('closeMobileDrawer');

        function openMobileDrawer() {
            if (mobileDrawer) mobileDrawer.classList.add('drawer-open');
            if (mobileDrawerOverlay) mobileDrawerOverlay.classList.add('overlay-open');
            document.body.style.overflow = 'hidden';
        }

        function closeMobileDrawerFn() {
            if (mobileDrawer) mobileDrawer.classList.remove('drawer-open');
            if (mobileDrawerOverlay) mobileDrawerOverlay.classList.remove('overlay-open');
            document.body.style.overflow = '';
        }

        if (mobileNavToggle) {
            mobileNavToggle.addEventListener('click', openMobileDrawer);
        }
        if (closeMobileDrawer) {
            closeMobileDrawer.addEventListener('click', closeMobileDrawerFn);
        }
        if (mobileDrawerOverlay) {
            mobileDrawerOverlay.addEventListener('click', closeMobileDrawerFn);
        }

        // Live File Upload Image Preview Handler (e.g. register.php)
        var fileInput = document.getElementById('profilePhotoInput');
        var previewImg = document.getElementById('imagePreview');
        var previewBox = document.getElementById('imagePreviewBox');

        if (fileInput && previewImg) {
            fileInput.addEventListener('change', function(e) {
                var file = e.target.files[0];
                if (file) {
                    var reader = new FileReader();
                    reader.onload = function(evt) {
                        previewImg.src = evt.target.result;
                        if (previewBox) previewBox.style.display = 'flex';
                    };
                    reader.readAsDataURL(file);
                }
            });
        }

        // Click to Preview Image Lightbox Modal Handler
        var modal = document.getElementById('imagePreviewModal');
        var modalImg = document.getElementById('previewModalImage');
        var modalCaption = document.getElementById('previewModalCaption');
        var closeModal = document.getElementById('closePreviewModal');

        if (modal && modalImg) {
            document.body.addEventListener('click', function(e) {
                var target = e.target;
                if (target.tagName === 'IMG' && target.id !== 'previewModalImage' && (target.closest('.profile-img-wrap') || target.closest('.profile-card') || target.src.includes('/images/'))) {
                    modal.style.display = 'flex';
                    modalImg.src = target.src;
                    modalCaption.innerText = target.alt || 'Profile Image Preview';
                }
            });

            if (closeModal) {
                closeModal.addEventListener('click', function() {
                    modal.style.display = 'none';
                });
            }

            modal.addEventListener('click', function(e) {
                if (e.target === modal) {
                    modal.style.display = 'none';
                }
            });
        }
    });
